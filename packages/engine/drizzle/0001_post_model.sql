-- The newsletter: one issue per language, from the `newsletter-sent:<launch>:<lang>` cursors, which
-- hold each campaign's id and report URL, and which also record an issue whose sibling never went out
WITH "sent" AS (
  SELECT split_part(c."key", ':', 2) AS launch, split_part(c."key", ':', 3) AS lang,
         CASE WHEN c."value" IS JSON OBJECT THEN c."value"::jsonb END AS issue
  FROM "cursors" c
  WHERE c."key" ~ '^newsletter-sent:[0-9]+:(en|es)$'
)
INSERT INTO "posts" ("launch_id", "channel", "account_id", "kind", "external_id", "url", "status", "published_at", "updated_at")
SELECT l."id", 'newsletter',
       (SELECT a."id" FROM "accounts" a WHERE a."network" = 'brevo' AND a."brand" = l."brand" AND a."is_primary" = 1 ORDER BY a."id" LIMIT 1),
       'issue:' || s.lang, s.issue ->> 'externalId', s.issue ->> 'url', 'live',
       COALESCE(p."published_at", to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
       COALESCE(p."published_at", to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
FROM "sent" s
JOIN "launches" l ON l."id"::text = s.launch
LEFT JOIN "posts" p ON p."launch_id" = l."id" AND p."channel" = 'newsletter' AND p."kind" IS NULL
WHERE s.issue ->> 'externalId' IS NOT NULL
ON CONFLICT DO NOTHING;--> statement-breakpoint
-- A newsletter row with no cursors left: its comma-joined ids in the order they were sent, English first
INSERT INTO "posts" ("launch_id", "channel", "account_id", "kind", "external_id", "url", "status", "published_at", "updated_at")
SELECT p."launch_id", 'newsletter',
       (SELECT a."id" FROM "accounts" a JOIN "launches" l ON l."id" = p."launch_id"
        WHERE a."network" = 'brevo' AND a."brand" = l."brand" AND a."is_primary" = 1 ORDER BY a."id" LIMIT 1),
       'issue:' || (ARRAY['en', 'es'])[ids.n], ids.id,
       CASE WHEN p."url" LIKE '%/' || split_part(p."external_id", ',', 1) THEN regexp_replace(p."url", '[^/]+$', ids.id)
            WHEN ids.n = 1 THEN p."url" END,
