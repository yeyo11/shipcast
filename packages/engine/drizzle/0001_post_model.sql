  AND NOT EXISTS (SELECT 1 FROM "posts" i WHERE i."launch_id" = p."launch_id" AND i."channel" = 'newsletter' AND i."kind" LIKE 'issue:%')
ON CONFLICT DO NOTHING;--> statement-breakpoint
