-- A channel's readings are its post's. The old newsletter readings stay with the launch: each is the
-- sum of both issues, so neither issue is theirs alone
UPDATE "metrics" m SET "post_id" = p."id"
FROM "posts" p
WHERE m."post_id" IS NULL AND p."launch_id" = m."launch_id" AND p."channel" = m."source" AND p."kind" = 'post'
  AND m."source" NOT IN ('blog', 'newsletter');--> statement-breakpoint

