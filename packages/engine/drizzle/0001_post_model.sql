-- Instagram's story and comment, kept in `instagram-story:<launch>` and `instagram-comment:<launch>`,
-- dated as the post they followed
WITH "extra" AS (
  SELECT split_part(c."key", ':', 2) AS launch, substring(c."key" from '^instagram-(story|comment):') AS what, c."value"
  FROM "cursors" c
  WHERE c."key" ~ '^instagram-(story|comment):[0-9]+$'
)
INSERT INTO "posts" ("launch_id", "channel", "account_id", "kind", "external_id", "url", "status", "published_at", "updated_at")
SELECT l."id", 'instagram',
       (SELECT a."id" FROM "accounts" a WHERE a."network" = 'instagram' AND a."brand" = l."brand" AND a."is_primary" = 1 ORDER BY a."id" LIMIT 1),
       e.what, e."value", NULL, 'live',
       COALESCE(p."published_at", to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
       COALESCE(p."published_at", to_char(statement_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
