/*
 * Copies the illustrations into design/specimen.html as static SVG, between its two
 * "illustrations" markers, so the specimen keeps opening from disk with no build and no server.
 * The React components stay the source; run this after changing one:
 *   pnpm illustrations:specimen
 * (through tsx: Node's type stripping does not read JSX.)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { renderToStaticMarkup } from 'react-dom/server';
import { ILLUSTRATIONS, ILLUSTRATION_NAMES } from '../src/components/illustrations/index.ts';

const SPECIMEN = new URL('../../../design/specimen.html', import.meta.url);
const START = '<!-- illustrations:start (generated by apps/web/scripts/illustrations-specimen.tsx) -->';
const END = '<!-- illustrations:end -->';

// One render for the whole gallery, so every scene's pattern ids are unique on the page
const gallery = renderToStaticMarkup(
  <div className="illos">
    {ILLUSTRATION_NAMES.map((name) => {
      const { component: Scene, use } = ILLUSTRATIONS[name];
      return (
        <figure key={name} className="illo">
          <Scene />
          <figcaption>
            <b>{name}</b>
            <span>{use}</span>
          </figcaption>
        </figure>
      );
    })}
  </div>,
);

const html = readFileSync(SPECIMEN, 'utf8');
const from = html.indexOf(START);
const to = html.indexOf(END);
if (from === -1 || to === -1 || to < from) throw new Error(`design/specimen.html has no "${START}" … "${END}" pair to fill`);
writeFileSync(SPECIMEN, `${html.slice(0, from + START.length)}\n    ${gallery.replaceAll('<figure', '\n      <figure').replace(/<\/div>$/, '\n    </div>')}\n    ${html.slice(to)}`);
console.log(`specimen.html: ${ILLUSTRATION_NAMES.length} illustrations`);
